//! Extracts each Chinese character's Mandarin reading from Unihan (docs/decisions.md, decision 31).
//!
//! `jespersen-unihan-zh OUT UNIHAN_READINGS` reads `Unihan_Readings.txt` (from `Unihan.zip`, pinned
//! in data/upstream/sources.toml) and writes, for every character with a Mandarin reading, the
//! one it most often has: the most frequent of `kHanyuPinlu` (counted in a frequency dictionary of
//! modern Chinese) where the character has one, otherwise the first of `kMandarin` (the most
//! customary), in numbered pinyin with `ü` written `v` (`mise run zh:characters` writes
//! data/derived/zh/characters.tsv).

use std::{collections::BTreeMap, env, error::Error, fmt::Write as _, fs, path::Path, process::ExitCode};

fn main() -> ExitCode {
    let args: Vec<String> = env::args().skip(1).collect();
    let result = match args.as_slice() {
        [out, readings] => extract(Path::new(readings), Path::new(out)),
        _ => Err("usage: jespersen-unihan-zh OUT UNIHAN_READINGS".into()),
    };
    match result {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("jespersen-unihan-zh: {error}");
            ExitCode::FAILURE
        }
    }
}

fn extract(readings: &Path, out: &Path) -> Result<(), Box<dyn Error>> {
    let text = fs::read_to_string(readings)?;
    let version = text
        .lines()
        .find_map(|line| line.strip_prefix("# Unicode Version "))
        .ok_or("no '# Unicode Version' line: is this Unihan_Readings.txt?")?;
    let mut table = String::new();
    writeln!(
        table,
        "# Mandarin readings of Chinese characters from Unihan (Unicode {version}): the most frequent in\n\
         # kHanyuPinlu, otherwise the first in kMandarin, in numbered pinyin with ü written v.\n\
         # Generated by jespersen-unihan-zh: do not edit; regenerate with\n\
         # `mise run zh:characters -- path/to/Unihan_Readings.txt`. Unicode's licence and notice apply:\n\
         # data/upstream/unihan/LICENSE."
    )?;
    // Each character's kMandarin readings, and its readings counted in kHanyuPinlu.
    let mut customary: BTreeMap<char, Vec<String>> = BTreeMap::new();
    let mut frequent: BTreeMap<char, Vec<(u32, String)>> = BTreeMap::new();
    for line in text.lines().filter(|line| !line.starts_with('#')) {
        let mut fields = line.split('\t');
        let (Some(code), Some(field @ ("kMandarin" | "kHanyuPinlu")), Some(value)) =
            (fields.next(), fields.next(), fields.next())
        else {
            continue;
        };
        let code = u32::from_str_radix(code.trim_start_matches("U+"), 16)?;
        let character = char::from_u32(code).ok_or_else(|| format!("U+{code:04X} is no character"))?;
        let unreadable = |reading: &str| format!("U+{code:04X}: cannot read {reading:?}");
        if field == "kMandarin" {
            let readings = value
                .split(' ')
                .map(|reading| numbered(reading).ok_or_else(|| unreadable(reading)));
            customary.insert(character, readings.collect::<Result<_, _>>()?);
        } else {
            let mut counted = Vec::new();
            for entry in value.split(' ') {
                let (reading, count) = entry
                    .strip_suffix(')')
                    .and_then(|entry| entry.split_once('('))
                    .ok_or_else(|| unreadable(entry))?;
                counted.push((count.parse()?, numbered(reading).ok_or_else(|| unreadable(reading))?));
            }
            frequent.insert(character, counted);
        }
    }
    if customary.len() < 40_000 {
        return Err(format!("only {} readings found", customary.len()).into());
    }
    for (character, readings) in &customary {
        let reading = frequent
            .get(character)
            .and_then(|counted| most_frequent(counted, readings))
            .or_else(|| readings.first())
            .ok_or_else(|| format!("{character}: no reading"))?;
        writeln!(table, "{character}\t{reading}")?;
    }
    fs::write(out, table)?;
    Ok(())
}

/// The reading counted most often, among `counted` (from `kHanyuPinlu`). The neutral tone counts
/// only where `customary` (`kMandarin`) has it too: 了 and 的 are le and de on their own, but 西 is
/// counted neutral mostly inside 东西 (dōngxi) and is xī on its own.
fn most_frequent<'a>(counted: &'a [(u32, String)], customary: &[String]) -> Option<&'a String> {
    let neutral_too = customary.iter().any(|reading| reading.ends_with('5'));
    counted
        .iter()
        .filter(|(_, reading)| neutral_too || !reading.ends_with('5'))
        .max_by_key(|(count, _)| *count)
        .map(|(_, reading)| reading)
}

/// A syllable in pinyin with tone marks (`zhōng`, `lǜ`, `ḿ`, `ê̄`) in numbered pinyin (`zhong1`,
/// `lv4`, `m2`, `ê1`); a syllable without a mark has the neutral tone (`le5`).
fn numbered(syllable: &str) -> Option<String> {
    let mut letters = String::new();
    let mut tone = 5;
    for c in syllable.chars() {
        let (letter, mark) = match c {
            'ā' => ('a', 1),
            'á' => ('a', 2),
            'ǎ' => ('a', 3),
            'à' => ('a', 4),
            'ē' => ('e', 1),
            'é' => ('e', 2),
            'ě' => ('e', 3),
            'è' => ('e', 4),
            'ī' => ('i', 1),
            'í' => ('i', 2),
            'ǐ' => ('i', 3),
            'ì' => ('i', 4),
            'ō' => ('o', 1),
            'ó' => ('o', 2),
            'ǒ' => ('o', 3),
            'ò' => ('o', 4),
            'ū' => ('u', 1),
            'ú' => ('u', 2),
            'ǔ' => ('u', 3),
            'ù' => ('u', 4),
            'ǖ' => ('v', 1),
            'ǘ' => ('v', 2),
            'ǚ' => ('v', 3),
            'ǜ' => ('v', 4),
            'ü' => ('v', 0),
            'ḿ' => ('m', 2),
            'ń' => ('n', 2),
            'ň' => ('n', 3),
            'ǹ' => ('n', 4),
            'ế' => ('ê', 2),
            'ề' => ('ê', 4),
            // Combining marks, after the letter they go on.
            '\u{0304}' => ('\0', 1),
            '\u{0301}' => ('\0', 2),
            '\u{030C}' => ('\0', 3),
            '\u{0300}' => ('\0', 4),
            'a'..='z' | 'ê' => (c, 0),
            _ => return None,
        };
        if letter != '\0' {
            letters.push(letter);
        }
        if mark != 0 {
            tone = mark;
        }
    }
    (!letters.is_empty()).then(|| format!("{letters}{tone}"))
}
