//! NST's `.pron` files: Latin-1, one entry per line, 51 fields separated by `;` (the numbers below
//! count from 0, as NST's documentation does). Each language keeps the entries jespersen may use and
//! writes them as one table, sorted and without repeats.

use std::{collections::BTreeSet, error::Error, fmt::Write as _, str::FromStr};

/// The languages of NST's lexicons.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Language {
    Danish,
    Swedish,
    Bokmal,
}

/// One entry kept: the word, its part of speech and its transcription in NST's SAMPA.
pub type Entry = (String, String, String);

/// The sets of the Swedish lexicon whose words NST bought (decision 42): the Enter list, which came
/// with its transcriptions, and the Telia lexicon's base forms and names.
const SWEDISH_BOUGHT: [&str; 4] = [
    "enter_se",
    "teliabaseforms_se",
    "telia_personnames_se",
    "telia_placenames_se",
];

/// The sets of the Bokmål lexicon whose words NST bought: the base forms of `NorKompLeks`, and
/// the names of people, places and companies from Onomastica.
const BOKMAL_BOUGHT: [&str; 4] = ["baseform_lex_no", "namelex_no", "company_names_no", "stock_names_no"];

impl Language {
    /// The file NST publishes for the language.
    fn file(self) -> &'static str {
        match self {
            Self::Danish => "dan030224NST.pron",
            Self::Swedish => "swe030224NST.pron",
            Self::Bokmal => "nor030224NST.pron",
        }
    }

    /// Fewer entries kept than this means the file is not the language's.
    fn minimum(self) -> usize {
        match self {
            Self::Danish => 200_000,
            Self::Swedish => 30_000,
            Self::Bokmal => 90_000,
        }
    }

    fn code(self) -> &'static str {
        match self {
            Self::Danish => "da",
            Self::Swedish => "sv",
            Self::Bokmal => "nb",
        }
    }

    /// Whether an entry from `source` (field 5) in `sets` (field 29) may be used. Every Danish
    /// entry was transcribed by hand; a Swedish or Bokmål one only when it was (`LEX`, not made by
    /// NST's inflector from bought base forms) and none of its sets was bought.
    fn keeps(self, source: &str, sets: &str) -> bool {
        let bought: &[&str] = match self {
            Self::Danish => return true,
            Self::Swedish => &SWEDISH_BOUGHT,
            Self::Bokmal => &BOKMAL_BOUGHT,
        };
        source == "LEX" && !sets.split('|').any(|set| bought.contains(&set))
    }

    /// The comment at the top of the table.
    fn header(self) -> String {
        let (name, middle) = match self {
            Self::Danish => (
                "Danish",
                "# in NST's SAMPA: \" and % stress, $ a syllable, : length, ? stød. Garbage entries and names\n\
                 # of several words are left out.",
            ),
            Self::Swedish => (
                "Swedish",
                "# in NST's SAMPA: \" accent 1, \"\" accent 2, % secondary stress, $ a syllable, : length.\n\
                 # Only the entries NST's transcribers wrote by hand outside the lexicons it bought\n\
                 # (decision 42): no inflector forms, nor the Enter list's or the Telia lexicon's words.\n\
                 # Garbage entries and names of several words are left out.",
            ),
            Self::Bokmal => (
                "Norwegian Bokmål",
                "# in NST's SAMPA: \" accent 1, \"\" accent 2, % secondary stress, $ a syllable, : length.\n\
                 # Only the entries NST's transcribers wrote by hand outside the lexicons it bought\n\
                 # (decision 42): no inflector forms, nor NorKompLeks' or Onomastica's words.\n\
                 # Garbage entries and names of several words are left out.",
            ),
        };
        let (file, code) = (self.file(), self.code());
        let generated = if self == Self::Danish { " " } else { "\n# " };
        format!(
            "# {name} words, their part of speech and pronunciation from NST's lexicon (Nordisk\n\
             # Språkteknologi, {file}; Språkbanken at the National Library of Norway, CC0 1.0),\n\
             {middle}{generated}Generated by jespersen-nst: do not edit; regenerate with\n\
             # `mise run data:nst:{code} -- path/to/{file}`.\n"
        )
    }
}

impl FromStr for Language {
    type Err = String;

    fn from_str(code: &str) -> Result<Self, Self::Err> {
        match code {
            "da" => Ok(Self::Danish),
            "sv" => Ok(Self::Swedish),
            "nb" => Ok(Self::Bokmal),
            _ => Err(format!("no NST lexicon for {code:?}: da, sv or nb")),
        }
    }
}

/// `bytes` read as Latin-1, where each byte is the character of the same number.
#[must_use]
pub fn latin1(bytes: &[u8]) -> String {
    bytes.iter().copied().map(char::from).collect()
}

/// The entries of `language`'s lexicon `text` that jespersen keeps: each word with its first part of
/// speech and its first transcription, without NST's ¤ (a name's mark, which says nothing about
/// the sounds). Garbage, words or transcriptions of several words (with `_`) and empty
/// transcriptions are left out.
///
/// # Errors
///
/// A line without NST's 51 fields.
pub fn entries(text: &str, language: Language) -> Result<BTreeSet<Entry>, Box<dyn Error>> {
    let mut entries = BTreeSet::new();
    for (number, line) in text.lines().enumerate() {
        let fields: Vec<&str> = line.split(';').collect();
        if fields.len() != 51 {
            return Err(format!("line {}: {} fields, not 51", number + 1, fields.len()).into());
        }
        let (word, pos, source, garbage, sampa, sets) =
            (fields[0], fields[1], fields[5], fields[7], fields[11], fields[29]);
        if garbage == "GARB" || word.contains('_') || sampa.contains('_') || sampa.is_empty() {
            continue;
        }
        if !language.keeps(source, sets) {
            continue;
        }
        let sampa = sampa.replace('¤', "");
        let pos = pos.split('|').next().unwrap_or_default();
        entries.insert((word.to_owned(), pos.to_owned(), sampa));
    }
    Ok(entries)
}

/// The table jespersen compiles from `language`'s lexicon `text`: its header, then one entry per
/// line, word, part of speech and transcription separated by tabs.
///
/// # Errors
///
/// A line without NST's 51 fields, or too few entries for `language`'s lexicon.
pub fn extract(text: &str, language: Language) -> Result<String, Box<dyn Error>> {
    let entries = entries(text, language)?;
    if entries.len() < language.minimum() {
        return Err(format!("only {} entries kept: is this {}?", entries.len(), language.file()).into());
    }
    let mut table = language.header();
    for (word, pos, sampa) in &entries {
        writeln!(table, "{word}\t{pos}\t{sampa}")?;
    }
    Ok(table)
}
